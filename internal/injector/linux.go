package injector

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/transos/transos/internal/schema"
	"github.com/transos/transos/internal/translator"
)

// InjectProfile writes the extracted state into persistent target environment configuration files
func InjectProfile(profile *schema.ConfigProfile) error {
	configDir := "target_output"
	if err := os.MkdirAll(configDir, 0755); err != nil {
		return fmt.Errorf("failed to create target output directory: %w", err)
	}

	envFilePath := filepath.Join(configDir, "transos_env.conf")
	var sb strings.Builder
	sb.WriteString("# Generated by TransOS Migration Engine (AST Path Translation Engine Active)\n\n")

	translatedCount := 0
	for k, v := range profile.Environment {
		// Pass value through AST Path Translator
		posixVal := translator.TranslatePathString(v)
		if posixVal != v {
			translatedCount++
		}
		sb.WriteString(fmt.Sprintf("export %s=\"%s\"\n", k, posixVal))
	}

	if err := os.WriteFile(envFilePath, []byte(sb.String()), 0644); err != nil {
		return fmt.Errorf("failed to write environment config: %w", err)
	}

	fmt.Printf("[+] AST Translator processed environment state (%d paths converted to POSIX standard).\n", translatedCount)
	fmt.Printf("[+] Successfully wrote persistent POSIX environment maps to: %s\n", envFilePath)
	return nil
}