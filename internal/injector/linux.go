package injector

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/transos/transos/internal/schema"
	"github.com/transos/transos/internal/translator"
)

// InjectProfile writes persistent env variables and generates the dependency downloader script
func InjectProfile(profile *schema.ConfigProfile) error {
	configDir := "target_output"
	if err := os.MkdirAll(configDir, 0755); err != nil {
		return fmt.Errorf("failed to create target output directory: %w", err)
	}

	// 1. Generate Persistent Environment Variables Configuration
	envFilePath := filepath.Join(configDir, "transos_env.conf")
	var envSb strings.Builder
	envSb.WriteString("# Generated by TransOS Migration Engine (AST Path Translation Engine Active)\n\n")

	translatedCount := 0
	for k, v := range profile.Environment {
		posixVal := translator.TranslatePathString(v)
		if posixVal != v {
			translatedCount++
		}
		envSb.WriteString(fmt.Sprintf("export %s=\"%s\"\n", k, posixVal))
	}

	if err := os.WriteFile(envFilePath, []byte(envSb.String()), 0644); err != nil {
		return fmt.Errorf("failed to write environment config: %w", err)
	}

	// 2. Generate Automated Dependency Downloader Script (install_dependencies.sh)
	scriptFilePath := filepath.Join(configDir, "install_dependencies.sh")
	var scriptSb strings.Builder

	scriptSb.WriteString("#!/usr/bin/env bash\n")
	scriptSb.WriteString("# TransOS Automated Dependency & Tool Installer Script\n")
	scriptSb.WriteString("# Generated from Windows Installed Applications Registry\n\n")
	scriptSb.WriteString("echo \"[TransOS] Updating local package databases...\"\n")
	scriptSb.WriteString("sudo apt-get update -y\n\n")
	scriptSb.WriteString("echo \"[TransOS] Installing mapped application dependencies...\"\n")

	mappedAppsCount := 0
	for k, winAppName := range profile.Registry {
		if strings.HasPrefix(k, "InstalledApp_") {
			if cmd, matched := translator.MapWindowsAppToLinux(winAppName); matched {
				scriptSb.WriteString(fmt.Sprintf("# Mapped from Windows App: %s\n", winAppName))
				scriptSb.WriteString(fmt.Sprintf("%s\n\n", cmd))
				mappedAppsCount++
			}
		}
	}

	scriptSb.WriteString("echo \"[TransOS] All mapped software dependencies installed successfully!\"\n")

	// Write executable script file with 0755 (chmod +x) permissions
	if err := os.WriteFile(scriptFilePath, []byte(scriptSb.String()), 0755); err != nil {
		return fmt.Errorf("failed to write dependency script: %w", err)
	}

	fmt.Printf("[+] AST Translator converted %d path variables to POSIX standard.\n", translatedCount)
	fmt.Printf("[+] Mapped %d installed software packages to Linux installers.\n", mappedAppsCount)
	fmt.Printf("[+] Generated Environment Maps: %s\n", envFilePath)
	fmt.Printf("[+] Generated Downloader Script: %s\n", scriptFilePath)

	return nil
}
